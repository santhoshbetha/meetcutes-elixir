defmodule MeetcutesWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :meetcutes

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_meetcutes_key",
    signing_salt: "XDuHdF5o",
    same_site: "Lax"
  ]

  socket "/socket", MeetcutesWeb.UserSocket,
    # websocket: true,
    websocket: [
      # Allows the origins configured through `CORS_ORIGINS` at runtime.
      check_origin: {MeetcutesWeb.Origin, :allowed?, []}
    ],
    longpoll: false

  # Dedicated LiveView socket used by the authenticated LiveDashboard.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :meetcutes,
    gzip: not code_reloading?,
    only: MeetcutesWeb.static_paths()

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :meetcutes
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # 1. Handle CORS for HTTP requests (must be above the Router).
  # The origin list is resolved at runtime from CORS_ORIGINS so the same image
  # works in development, staging and self-hosted production.
  plug CORSPlug,
    origin: &MeetcutesWeb.Origin.cors_origins/0,
    allow_headers: ["content-type", "authorization", "accept"],
    methods: ["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    length: 8_000_000,
    json_decoder: Phoenix.json_library(),
    body_reader: {MeetcutesWeb.RawBodyReader, :read_body, []}

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug MeetcutesWeb.Router
end
