# Configure your database.
#
# `DATABASE_URL` (loaded from `.env` by config/config.exs) points development
# at the hosted Postgres instance. Without it we fall back to the local
# docker/postgres defaults so the app still boots offline.
database_url = System.get_env("DATABASE_URL")

repo_config =
  if database_url do
    uri = URI.parse(database_url)
    query = URI.decode_query(uri.query || "")
    ssl? = Map.get(query, "sslmode") in ["require", "verify-ca", "verify-full"]
    query = Map.drop(query, ["sslmode"])
    encoded_query = if map_size(query) == 0, do: nil, else: URI.encode_query(query)
    clean_url = %{uri | query: encoded_query} |> URI.to_string()

    [
      url: clean_url,
      ssl: ssl?,
      stacktrace: true,
      show_sensitive_data_on_connection_error: false,
      pool_size: 5
    ]
  else
    [
      username: "postgres",
      password: "postgres",
      hostname: "localhost",
      database: "meetcutes_dev",
      stacktrace: true,
      show_sensitive_data_on_connection_error: true,
      pool_size: 10
    ]
  end

config :meetcutes, Meetcutes.Repo, repo_config

